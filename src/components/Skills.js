export default function Skills() {
  const ref = useRef(null);
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const obs = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            setVisible(true);
            obs.unobserve(el);
          }
        });
      },
      { threshold: 0.12 }
    );
    obs.observe(el);
    return () => obs.disconnect();
  }, []);

  return (
    <section id="skills" ref={ref} className={`skills-section ${visible ? 'visible' : ''}`}>
      <div className="skills-inner">
        <h2>Skills</h2>
        <p className="skills-sub"> THE TECHNOLOGIES I WORK WITH :</p>
        <div className="skills-grid">
          {SKILLS.map((s, idx) => (
            <div key={s.name} className="skill-card" title={s.name} style={{ '--i': idx }}>
              <img src={s.icon} alt={s.name} loading="lazy" />
              <span>{s.name}</span>
            </div>
          ))}
        </div>
      </div>
    </section>
  );
}
